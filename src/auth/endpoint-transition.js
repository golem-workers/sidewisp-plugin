import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { createDeviceAuthorizationClient } from './device-authorization.js';
import { inspectCredential } from './credential-status.js';
import { createFileCredentialStore } from './credentials.js';
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const sourceOrigin = 'https://staging-api.sidewisp.com';
const destinationOrigin = 'https://api.sidewisp.com';
async function source({stateDir, configFile}) {
 if (!path.isAbsolute(stateDir) || !path.isAbsolute(configFile)) throw Error('absolute_profile_paths_required');
 const configBytes=await fs.readFile(configFile), config=JSON.parse(configBytes);
 if (config.plugins?.entries?.sidewisp?.config?.endpoint !== sourceOrigin) throw Error('source_endpoint_mismatch');
 const bytes=await fs.readFile(path.join(stateDir,'sidewisp','installation.json'));
 const credential=await createFileCredentialStore({stateDir}).read();
 if (!credential || credential.status!=='active') throw Error('source_binding_required');
 return {credential,sourceFingerprint:hash(bytes),configFingerprint:hash(configBytes)};
}
export async function planEndpointTransition(options) {
 const original=await source(options);
 const plan={schema:'sidewisp.endpoint-transition.v1',stateDir:options.stateDir,configFile:options.configFile,sourceEndpoint:sourceOrigin,targetEndpoint:destinationOrigin,sourceInstallationId:original.credential.installationId,sourceFingerprint:original.sourceFingerprint,configFingerprint:original.configFingerprint};
 const confirmation=hash(JSON.stringify(plan));
 return {...plan,confirmation,candidateStateDir:path.join(options.stateDir,'sidewisp-transitions',confirmation,'candidate')};
}
async function verify(plan) {
 if(plan.schema!=='sidewisp.endpoint-transition.v1' || plan.sourceEndpoint!==sourceOrigin || plan.targetEndpoint!==destinationOrigin)throw Error('invalid_transition_plan');
 const current=await planEndpointTransition(plan);
 if (current.confirmation!==plan.confirmation || current.candidateStateDir!==plan.candidateStateDir) throw Error('source_profile_changed');
 return current;
}
export async function beginEndpointTransition({plan,confirmation,requestId,fetchImpl=globalThis.fetch}) {
 await verify(plan);
 if (confirmation!==plan.confirmation) throw Error('explicit_host_confirmation_required');
 const current=await source(plan);
 if(await inspectCredential({endpoint:sourceOrigin,credential:current.credential,fetchImpl})!=='active')throw Error('source_binding_unavailable');
 // No old secret is copied or sent to the destination. An independent proof is
 // generated by the normal client; the initiating account must approve in-app.
 const client=createDeviceAuthorizationClient({endpoint:destinationOrigin,stateDir:plan.candidateStateDir,fetchImpl});
 return client.begin({id:requestId,runtime:'openclaw'});
}
export async function pollEndpointTransition({plan,fetchImpl=globalThis.fetch}) {
 await verify(plan);
 return createDeviceAuthorizationClient({endpoint:destinationOrigin,stateDir:plan.candidateStateDir,fetchImpl}).poll();
}
export async function verifyEndpointTransitionReady({plan,fetchImpl=globalThis.fetch}) {
 await verify(plan);
 const candidate=await createFileCredentialStore({stateDir:plan.candidateStateDir}).read();
 if (!candidate || candidate.installationId===plan.sourceInstallationId || await inspectCredential({endpoint:destinationOrigin,credential:candidate,fetchImpl})!=='active')throw Error('new_production_authorization_required');
 // Readiness is not activation. This module deliberately cannot write active
 // configuration, installation.json, spool, cursors, manager state or old data.
 return {status:'ready_for_confirmed_host_cutover',sourceInstallationId:plan.sourceInstallationId,targetInstallationId:candidate.installationId,bindingChanged:false};
}
